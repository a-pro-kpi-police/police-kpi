export function kpiIndicator(item, lang) {
  if (!item) return ''
  return lang === 'kk' ? (INDICATORS_KK[item.code] || item.indicator || '') : (item.indicator || '')
}

export function kpiSearchText(item) {
  return [item?.code, item?.indicator, INDICATORS_KK[item?.code]]
    .filter(Boolean)
    .join(' ')
    .toLocaleLowerCase()
}

